def team_rows(n: int) -> list[tuple[str, str]]:
    if n > len(TEAM_CITIES):
        raise ValueError(f"at most {len(TEAM_CITIES)} demo teams supported")
    return [(TEAM_CITIES[i], TEAM_NICKNAMES[i]) for i in range(n)]


def player_names(rng: np.random.Generator, n: int) -> list[tuple[str, str]]:
    """Unique fictional (first, last) pairs."""
    seen: set[tuple[str, str]] = set()
    out: list[tuple[str, str]] = []
    while len(out) < n:
        pair = (str(rng.choice(FIRST_NAMES)), str(rng.choice(LAST_NAMES)))
        if pair in seen:
            pair = (pair[0], f"{pair[1]}-{rng.choice(LAST_NAMES)}")
            if pair in seen:
                continue
        seen.add(pair)
        out.append(pair)
    return out
