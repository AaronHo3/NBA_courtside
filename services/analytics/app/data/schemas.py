FAMILIES: tuple[str, ...] = tuple(_SCHEMAS)
# Families produced by exporting reviewed application state, not by ingestion or the demo generator.
SNAPSHOT_FAMILIES: tuple[str, ...] = ("annotation_snapshots", "evidence_snapshots")
SEASONAL_FAMILIES: tuple[str, ...] = tuple(
    f for f in FAMILIES if any(n == "season" for n, _ in _SCHEMAS[f])
)
SEASON_TYPES: tuple[str, ...] = ("Regular Season", "Playoffs", "Pre Season")


def schema_for(family: str) -> pa.Schema:
    if family not in _SCHEMAS:
        raise KeyError(f"unknown dataset family {family!r}")
    return pa.schema(_SCHEMAS[family])


def conform(df: pd.DataFrame, family: str) -> pd.DataFrame:
    """Return a copy with exactly the schema's columns (missing ones null) in schema order."""
    schema = schema_for(family)
    out = df.copy()
    for name in schema.names:
        if name not in out.columns:
            out[name] = None
    extra = [c for c in out.columns if c not in schema.names]
    return out.drop(columns=extra)[schema.names]


def to_arrow(df: pd.DataFrame, family: str) -> pa.Table:
    conformed = conform(df, family)
    return pa.Table.from_pandas(conformed, schema=schema_for(family), preserve_index=False)
